"""R-0033: generate independent dimensional substitutes; align official USB STEP.
Run with FreeCAD 0.20 bin/python.exe, from the A-2 design worktree.
No electrical or footprint geometry is generated by this script.
"""
import FreeCAD as App
import Part
from pathlib import Path
import json, hashlib

root = Path('01_New_Design/kicad_direct')
out = root / 'models'
out.mkdir(exist_ok=True)
black = (0.07, 0.07, 0.075)
metal = (0.72, 0.73, 0.75)

def box(x,y,z,l,w,h):
    return Part.makeBox(l,w,h,App.Vector(x,y,z))

def export(name, parts):
    solid=Part.makeCompound([s for s,c in parts])
    solid.exportStep(str(out/(name+'.step')))
    step=out/(name+'.step')
    step.write_text('\n'.join(line.rstrip() for line in step.read_text().splitlines())+'\n')
    # VRML units are 0.1 inch in KiCad; matching STEP is in mm.
    lines=['#VRML V2.0 utf8','# Independent simplified model, R-0033; not manufacturer CAD.']
    for shape,color in parts:
        vertices,triangles=shape.tessellate(0.02)
        lines += ['Shape { appearance Appearance { material Material { diffuseColor %g %g %g } } geometry IndexedFaceSet { solid FALSE coord Coordinate { point ['%color,
                  ',\n'.join('%.8f %.8f %.8f'%(v.x/2.54,v.y/2.54,v.z/2.54) for v in vertices),
                  '] } coordIndex [', ',\n'.join('%d,%d,%d,-1'%t for t in triangles), '] } }']
    (out/(name+'.wrl')).write_text('\n'.join(lines)+'\n',encoding='utf-8')
    return [solid.BoundBox.XMin,solid.BoundBox.YMin,solid.BoundBox.ZMin,solid.BoundBox.XMax,solid.BoundBox.YMax,solid.BoundBox.ZMax]

# TI DPY0002A: 1.0 x 0.6 mm nominal body; maximum height 0.45 mm;
# two 0.25 x 0.50 terminals, nominal terminal pitch 0.65 mm.
# No manufacturer logo; index stripe is illustrative only.
dpy=[(box(-.5,-.3,.025,1,.6,.425),black)]
for x in [-.325,.325]:dpy.append((box(x-.125,-.25,0,.25,.5,.025),metal))
dpy.append((box(-.44,-.25,.449,.06,.5,.001),(.5,.5,.5)))
dimensions={'DPY0002A_simplified':export('DPY0002A_simplified',dpy)}

# Samtec SH drawing CQ: pitch 2.54, width 4*2.54, body depth 2.54,
# body height 3.05, square pins .64, exposed post B=5.84, tail C=4.57.
# Solder flat 2.04 centered on existing pads. Rear body starts at 3.55.
# The provisional footprint F.Fab body is NOT used to distort this model.
parts=[(box(-5.08,-6.09,0,10.16,2.54,3.05),black)]
for x in [-3.81,-1.27,1.27,3.81]:
    # Section in y/z, simplified formed pin with a diagonal transition.
    yz=[(1.02,0),(-1.02,0),(-3.0,1.46),(-11.93,1.46),(-11.93,2.10),(-2.8,2.10),(-.81,.64),(1.02,.64)]
    points=[App.Vector(x-.32,y,z) for y,z in yz]
    parts.append((Part.Face(Part.makePolygon(points+[points[0]])).extrude(App.Vector(.64,0,0)),metal))
dimensions['TSM_104_01_T_SH_simplified']=export('TSM_104_01_T_SH_simplified',parts)

# The vendor STEP is kept local (redistribution permission is unconfirmed).
# Native axes: width X, thickness Y, length Z, mouth Z=0.
# KiCad local model axes: X length, Y=-PCB-Y, Z up.
vendor=out/'vendor/Molex_480372200.step'
source=Part.read(str(vendor))
m=App.Matrix();m.A11=0;m.A12=0;m.A13=1;m.A14=9.375
m.A21=1;m.A22=0;m.A23=0;m.A24=0
m.A31=0;m.A32=1;m.A33=0;m.A34=-.1
aligned=source.transformGeometry(m)
aligned.exportStep(str(out/'vendor/Molex_480372200_aligned.step'))
dimensions['Molex_480372200_aligned']=[aligned.BoundBox.XMin,aligned.BoundBox.YMin,aligned.BoundBox.ZMin,aligned.BoundBox.XMax,aligned.BoundBox.YMax,aligned.BoundBox.ZMax]
(root/'reports/3d_models/model_dimensions.json').write_text(json.dumps(dimensions,indent=2)+'\n')
print(json.dumps(dimensions,indent=2))
